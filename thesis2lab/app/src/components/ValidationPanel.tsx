import { useState } from 'react'
import { DataTable } from '../charts/Charts'
import type { ValidationReport } from '../research/types'
import type { EffectiveStatus } from '../research/status'

const sym = (v: string) => (v === 'pass' ? 'Pass' : v === 'fail' ? 'Fail' : v === 'not_assessed' ? 'Not assessed' : 'Not applicable')

export function ValidationPanel({ report, eff }: { report?: ValidationReport; eff: EffectiveStatus }) {
  const [open, setOpen] = useState(false)
  if (!report) return <p>No validation report exists for this experiment. {eff.declared === 'BLOCKED' ? 'Nothing can be computed while it is blocked.' : ''}</p>
  const s = report.summary
  return (
    <div>
      <dl className="facts">
        <div><dt>Technical execution</dt><dd className={`res-${s.technical_execution}`}>{sym(s.technical_execution)}</dd></div>
        <div><dt>Numerical agreement</dt><dd className={`res-${s.numerical_agreement}`}>{sym(s.numerical_agreement)}</dd></div>
        <div><dt>Methodological fidelity</dt><dd className={`res-${s.methodological_fidelity}`}>{sym(s.methodological_fidelity)}</dd></div>
        <div><dt>Repeatability</dt><dd className={`res-${s.repeatability}`}>{sym(s.repeatability)}</dd></div>
        <div><dt>Independent review</dt><dd className={`res-${report.independent_review.status === 'completed' ? 'pass' : 'pending'}`}>{report.independent_review.status === 'completed' ? `Completed by ${report.independent_review.reviewer}` : 'Pending (nobody has signed off)'}</dd></div>
        <div><dt>Checks passed</dt><dd>{s.checks_passed} of {s.checks_total}</dd></div>
      </dl>
      <p className="muted small">Generated by program execution at {report.generated_at} on code commit {report.code_version.git_commit?.slice(0, 10) ?? 'unknown'}{report.code_version.working_tree_dirty ? ' (uncommitted changes)' : ''}. {Object.entries(report.dependency_versions).map(([k, v]) => `${k} ${v}`).join('; ')}.</p>
      {report.remaining_uncertainty.length > 0 && (
        <>
          <h4>Remaining uncertainty</h4>
          <ul>{report.remaining_uncertainty.map((u) => <li key={u}>{u}</li>)}</ul>
        </>
      )}
      <button type="button" className="link-button" aria-expanded={open} onClick={() => setOpen(!open)}>{open ? 'Hide' : 'Show'} all {report.checks.length} checks</button>
      {open && (
        <DataTable caption="Every check executed" columns={['check', 'kind', 'required', 'reference', 'result']}
          rows={report.checks.map((c) => [c.id, c.kind, c.required === false ? 'no' : 'yes', c.reference_kind?.replace(/_/g, ' ') ?? '', c.pass ? 'pass' : 'FAIL'])} />
      )}
    </div>
  )
}
