import csv, tempfile, os

db_path = "02_screening/full_text/full_text_screening_database.csv"
log_path = "02_screening/exclusion_log/exclusion_log.csv"

with open(db_path, newline='', encoding='utf-8') as f:
    reader = csv.DictReader(f)
    fieldnames = reader.fieldnames
    rows = list(reader)

excludes = {
    "R8AD13170998A": {
        "exclusion_reason": "E01",
        "exclusion_reason_detail": "Methods paper on using crowd-sourced data to study public services in political science research, drawing on the authors' NextDrop water-intermittency crowd-sourcing project in Bangalore as one illustration among several suggested applications (protest politics, corruption, public opinion, law and order). The paper's actual contribution is methodological -- strategies for groundtruthing, correcting selection bias, causal inference via cluster randomization, and organizational/technical partnerships for crowd-sourced-data research -- not a primary empirical study of legal-administrative water-access mechanisms. Water access is a case study for the methodology, not the paper's subject.",
    },
    "RFAED90B6DD97": {
        "exclusion_reason": "E05",
        "exclusion_reason_detail": "Explicitly self-labeled 'Paper type: General review' -- a narrative literature survey (JSTOR/EBSCOhost database search, hand-coded themes) of gender and water-governance issues in Mexico, with no original empirical data collection of its own (no interviews, no fieldwork, no survey; the author explicitly states future research will add case studies and fieldwork observations that this review lacks). All substantive findings are citations to other authors' studies and government/NGO reports rather than new evidence generated by this paper.",
    },
}

includes = {
    "RACFFE4F7F72C": "Extracted as S548. Qualitative case study (34 semi-structured interviews, 3 community workshops, key informant interviews, documentary review) of institutional adaptation for water management in Mbire District, Zimbabwe. Documents Zimbabwe's water-law framework (Water Act 1998, ZINWA Act 1998, Environmental Management Act 2002, Rural District Councils Act 1996, Public Health Act 2002) and concrete access mechanisms: institutional fragmentation and non-presence of the formally mandated Catchment/Sub-Catchment Councils and ZINWA in this rural area (over 90% of respondents had no knowledge of CCs/SCCs), RDC by-law enforcement (streambank-cultivation ban) contested by and modified in response to local livelihoods pressure, chronic borehole shortage (up to 2,000 persons per functioning borehole vs. a 250-person recommended maximum), and conflict between EMA's national-regulation enforcement and RDC/traditional-authority locally negotiated accommodation. CASP Qualitative Studies Checklist (qualitative).",
    "RCC0D2A422FD2": "Extracted as S549. Mixed-methods study (62 semi-structured household interviews, transect walks, photo diaries, expert interviews) of de facto privatisation and uneven access to land and water in peri-urban Greater Accra, Ghana. Documents Ghana's water/land legal framework (Water Resources Commission Act 1996, Water Use Regulations 2001, GWCL/MMDA/CWSA statutory mandate split, customary land tenure law, Title Registration Act 1986) and concrete household-level access mechanisms: unlicensed/unregistered de facto private control of groundwater by landowners despite a legal permit requirement, private water-vendor pricing 3-20x the official utility rate, income-stratified choice of water provider (bulk tanker vs. neighbourhood vendor), land-tenure insecurity from multiple sale of the same plot amid an unresolved 20-year chieftaincy dispute, and extra-legal 'digging fee'/asafo money payments required to begin construction. MMAT (mixed methods).",
}

reviewer = "Claude-AI-fulltext-2026-09-21"
changed = 0
for r in rows:
    rid = r["record_id"]
    if rid in excludes:
        assert r["full_text_decision"] == "" and r["final_decision"] == "", f"{rid} already decided"
        d = excludes[rid]
        r["full_text_decision"] = "exclude"
        r["final_decision"] = "exclude"
        r["reviewer_1"] = reviewer
        r["exclusion_reason"] = d["exclusion_reason"]
        r["exclusion_reason_detail"] = d["exclusion_reason_detail"]
        changed += 1
    elif rid in includes:
        assert r["full_text_decision"] == "" and r["final_decision"] == "", f"{rid} already decided"
        r["full_text_decision"] = "include"
        r["final_decision"] = "include"
        r["reviewer_1"] = reviewer
        r["notes"] = includes[rid]
        changed += 1

assert changed == len(excludes) + len(includes), f"expected {len(excludes)+len(includes)}, got {changed}"

fd, tmp = tempfile.mkstemp(dir="02_screening/full_text")
with os.fdopen(fd, "w", newline='', encoding='utf-8') as f:
    writer = csv.DictWriter(f, fieldnames=fieldnames)
    writer.writeheader()
    writer.writerows(rows)
os.replace(tmp, db_path)

with open(log_path, newline='', encoding='utf-8') as f:
    reader = csv.DictReader(f)
    log_fieldnames = reader.fieldnames
    log_rows = list(reader)

id_to_row = {r["record_id"]: r for r in rows}
for rid, d in excludes.items():
    r = id_to_row[rid]
    log_rows.append({
        "record_id": rid,
        "title": r["title"],
        "authors": r["authors"],
        "year": r["year"],
        "stage": "full_text",
        "exclusion_code": d["exclusion_reason"],
        "exclusion_reason_detail": d["exclusion_reason_detail"],
        "reviewer": reviewer,
        "date": "2026-09-21",
    })

fd, tmp = tempfile.mkstemp(dir="02_screening/exclusion_log")
with os.fdopen(fd, "w", newline='', encoding='utf-8') as f:
    writer = csv.DictWriter(f, fieldnames=log_fieldnames)
    writer.writeheader()
    writer.writerows(log_rows)
os.replace(tmp, log_path)

print("done, db changed", changed, "log rows now", len(log_rows))
