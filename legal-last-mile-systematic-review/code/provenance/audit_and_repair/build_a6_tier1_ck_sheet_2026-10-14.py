"""2026-10-14 (open item A6, tier 1 of the reviewer-2 full-text queue): the 18 tier-1 rows that already carry a blind second-model decision (Codex gpt-5.6-sol and Gemini gemini-3.1-flash-lite, 2026-10-03/04).
Writes a CK ruling sheet (CSV and Markdown), conflicts first, so that the researcher can issue human `CK` decisions row by row. READ-ONLY on every database: nothing in the screening, extraction or effect files changes.
Order: (1) rows where a second model's decision differs from the Pass-1 AI decision, (2) rows where only the exclusion code differs, (3) rows where both models agree with the AI.
The sheet puts the ruling columns before the models' rationales, so that a decision can be formed first (the blinding principle of REVIEWER_2_CHECKLIST.md). Run from legal-last-mile-systematic-review/."""
import csv, json, os, re, sys
csv.field_size_limit(sys.maxsize)
Q = '02_screening/full_text/full_text_reviewer_2_priority_queue_2026-09-28.csv'
FT = '02_screening/full_text/full_text_screening_database.csv'
OUT = '02_screening/full_text/A6_TIER1_SECOND_MODEL_CK_SHEET_2026-10-14'
if os.path.exists(OUT + '.csv') and any(r['ck_decision (include/exclude)'].strip() or r['ck_comment'].strip() for r in csv.DictReader(open(OUT + '.csv', encoding='utf-8'))) and '--force' not in sys.argv:
    sys.exit('Refusing to overwrite a sheet that already holds CK rulings or comments (pass --force to rebuild it).')
q = [r for r in csv.DictReader(open(Q, encoding='utf-8')) if r['priority_tier'] == '1']
ft = {r['record_id']: r for r in csv.DictReader(open(FT, encoding='utf-8'))}


SPLIT = re.compile(r'(?<!\bp)(?<!\bpp)(?<!\bal)(?<!\bet)(?<!\bvs)(?<!\bca)(?<!\bNo)\.\s+(?=[A-Z“"(])')


def first_sentence(t, n=330):
    t = ' '.join((t or '').split())
    m = SPLIT.search(t)
    if m and m.start() < n:
        return t[:m.start() + 1]
    return t[:n].rstrip() + ('…' if len(t) > n else '')


TAG = re.compile(r'^[^.]{0,90}\b(19|20)\d\d[a-z]?\.\s*')   # the leading 'Author Year.' citation tag of exclusion_reason_detail


def prior_ck(notes):
    """A ruling already made by CK on this record (A16 and later adjudications), taken from the notes field; '' if none."""
    for part in notes.split(' | '):
        if 'adjudication' in part and 'by CK' in part:
            return part.strip()
    return ''


rows = []
for r in q:
    rid = r['record_id']; f = ft[rid]
    if f['reviewer_2'][:5] not in ('Codex', 'Gemin'):
        continue
    c = json.load(open(f'_reviewer2_codex/results/{rid}.json', encoding='utf-8'))['parsed']
    gp = f'_reviewer2_codex/results_gemini/{rid}.json'
    g = json.load(open(gp, encoding='utf-8'))['parsed'] if os.path.exists(gp) else {'decision': '', 'exclusion_code': '', 'rationale': ''}
    ai, aic = r['ai_decision'], r['ai_exclusion_code']
    if c['decision'] != ai or (g['decision'] and g['decision'] != ai):
        grp = 1
    elif c.get('exclusion_code', '') != aic and ai == 'exclude':
        grp = 2
    else:
        grp = 3
    rows.append({'order': 0, 'group': {1: 'A. model decision differs from the AI', 2: 'B. only the exclusion code differs', 3: 'C. both models agree with the AI'}[grp], '_g': grp,
                 'record_id': rid, 'study_id': r['study_id'], 'citation': f"{r['authors']} ({r['year']}). {r['title']}", 'doi': r['doi'],
                 'full_text_status': r['full_text_status'], 'pass1_ai_decision': ai, 'pass1_ai_code': aic,
                 'codex_decision': c['decision'], 'codex_code': c.get('exclusion_code', ''), 'gemini_decision': g['decision'], 'gemini_code': g.get('exclusion_code', ''),
                 'db_conflict_flag': f['conflict'], 'ck_decision (include/exclude)': '', 'ck_exclusion_code (E01-E12)': '', 'ck_comment': '',
                 'codex_rationale_1line': first_sentence(c.get('rationale', '')), 'gemini_rationale_1line': first_sentence(g.get('rationale', '')),
                 'pass1_ai_reasoning_1line': TAG.sub('', ' '.join(f['exclusion_reason_detail'].split())) if ai == 'exclude' and f['exclusion_reason_detail'].strip() else '(no written rationale stored for this include; see the extraction row)',
                 'prior_ck_ruling': prior_ck(f['notes'])})
rows.sort(key=lambda x: (x['_g'], x['pass1_ai_decision'] != 'exclude', x['record_id']))
for i, x in enumerate(rows, 1):
    x['order'] = i
fields = [k for k in rows[0] if k != '_g']
with open(OUT + '.csv', 'w', newline='', encoding='utf-8') as fh:
    w = csv.DictWriter(fh, fieldnames=fields, extrasaction='ignore', lineterminator='\r\n'); w.writeheader(); w.writerows(rows)
L = ['# A6 tier 1: the 18 rows with a blind second-model decision (for human `CK` rulings)', '',
     '*Generated by `code/provenance/audit_and_repair/build_a6_tier1_ck_sheet_2026-10-14.py`; read-only. Codex = `gpt-5.6-sol`, Gemini = `gemini-3.1-flash-lite`, both blind to the Pass-1 AI decision (2026-10-03/04). '
     'AI-versus-AI, not a human check. Fill `ck_decision`, `ck_exclusion_code` and `ck_comment` in the CSV (same order).*', '']
cur = None
for x in rows:
    if x['group'] != cur:
        cur = x['group']; L += [f'## {cur}', '', '| # | record / study | citation | Pass-1 AI | Codex | Gemini | 1-line rationale (Codex; Gemini if it differs) |', '|---|---|---|---|---|---|---|']
    rat = x['codex_rationale_1line'] + ((' — *Gemini:* ' + x['gemini_rationale_1line']) if x['gemini_decision'] and x['gemini_decision'] != x['codex_decision'] else '')
    if x['prior_ck_ruling']:
        rat += ' — **Prior CK ruling:** ' + x['prior_ck_ruling']
    L.append(f"| {x['order']} | `{x['record_id']}` {x['study_id']} | {x['citation'][:150]} | {x['pass1_ai_decision']} {x['pass1_ai_code']} | {x['codex_decision']} {x['codex_code']} | {x['gemini_decision']} {x['gemini_code']} | {rat} |")
    if L[-1] and x is rows[-1] or (rows[rows.index(x) + 1]['group'] != cur if x is not rows[-1] else False):
        L.append('')
open(OUT + '.md', 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('wrote', OUT + '.csv', 'and .md;', len(rows), 'rows; groups', {g: sum(1 for x in rows if x['_g'] == g) for g in (1, 2, 3)})
