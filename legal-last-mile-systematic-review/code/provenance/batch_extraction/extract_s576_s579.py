def main():
    with open(EXTRACT_DB, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        fieldnames = reader.fieldnames
        rows = list(reader)

    existing_ids = {row["study_id"] for row in rows}
    build(fieldnames)
    for row in ROWS:
        assert row["study_id"] not in existing_ids, f"{row['study_id']} already exists"
        row.pop("source_document_note", None)
        extra = set(row.keys()) - set(fieldnames)
        assert not extra, f"unexpected fields {extra} for {row['study_id']}"

    rows.extend(ROWS)

    fd, tmp_path = tempfile.mkstemp(dir=os.path.dirname(EXTRACT_DB), suffix=".csv")
    with os.fdopen(fd, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
    os.replace(tmp_path, EXTRACT_DB)

    print(f"done, extraction rows now {len(rows)}")


if __name__ == "__main__":
    main()
