#!/usr/bin/env python3
"""Does each effect-size row's exposure match the wording of the synthesis family it was assigned to? (a draft audit; nothing is changed)

PROJECT_SPEC.md section 8 defines the candidate synthesis families by their exposures:
  A  legal recognition and access: legal recognition, recognized vs unrecognized settlement, formal vs informal tenure, service eligibility, land title
  B  administrative assistance and access: bureaucratic assistance, administrative facilitation, procedural simplification
  C  administrative/legal barriers and access inequality: legal or administrative barriers, documentation, eligibility restrictions, formalization barriers
Rows were assigned to A/B/C (or left blank as non-fit) by judgement in 2026-09-28; because no family reached pooling, the assignments only organise the SWiM
write-ups. This script applies the spec's own exposure words as keyword cues to each row's `exposure_definition` and reports which rows carry at least one cue
for their family and which do not ("outside the definition's wording"). It is a mechanical read, not a validated coding: a row outside the wording may still be
a defensible, looser fit, and a row with a cue may not really fit. Writes 05_analysis/effect_sizes/FAMILY_FIT_AUDIT_2026-10-04.{csv,md}. Run from the project root."""
import csv
import re
import sys
from collections import Counter
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import current_figures as cf  # noqa: E402

OUT_CSV = cf.ROOT / '05_analysis/effect_sizes/FAMILY_FIT_AUDIT_2026-10-04.csv'
OUT_MD = cf.ROOT / '05_analysis/effect_sizes/FAMILY_FIT_AUDIT_2026-10-04.md'
CUES = {
    'A': re.compile(r'recogni|notif|incorporat|legal (status|title|land)|tenure|home-?ownership|\btitl|zon(ed|ing|e)\b|ZEIS|eligib|formal (household )?(water )?connection|customary|autonom', re.I),
    'B': re.compile(r'assist|facilitat|simplif|bureaucra|help (completing|with)|application', re.I),
    'C': re.compile(r'barrier|documentation|eligib\w* restrict|formali[sz]ation|inequit|inequal|disconnection|enforcement|weight rule|unregistered|hukou|restrict|redress', re.I),
}
DEF = {'A': 'legal recognition / tenure / eligibility / title', 'B': 'bureaucratic assistance / facilitation / simplification', 'C': 'legal or administrative barriers / documentation / eligibility restrictions'}
FIELDS = ['study_id', 'synthesis_family', 'fit', 'cue_found', 'outcome_family', 'exposure_definition']


def build():
    rows = []
    for r in cf.read('es'):
        fam = r['synthesis_family']
        if fam not in CUES:
            continue
        m = CUES[fam].search(r['exposure_definition'])
        rows.append({'study_id': r['study_id'], 'synthesis_family': fam, 'fit': 'cue in definition wording' if m else 'outside the definition wording', 'cue_found': m.group(0).lower() if m else '',
                     'outcome_family': r['outcome_family'], 'exposure_definition': r['exposure_definition'][:160].replace('\n', ' ')})
    rows.sort(key=lambda x: (x['synthesis_family'], x['fit'] != 'outside the definition wording', int(x['study_id'][1:])))
    return rows


def render(rows):
    n_all = len(cf.read('es'))
    by = {f: Counter(r['fit'] for r in rows if r['synthesis_family'] == f) for f in CUES}
    out = [r for r in rows if r['fit'].startswith('outside')]
    L = ['# Do the effect-size rows fit the wording of their synthesis family?', '',
         f"Generated by `code/analysis/audit_effect_size_families.py`. {len(rows)} of {n_all} effect-size rows carry a family (A, B or C); the rest are non-fit rows. The spec's exposure words (`PROJECT_SPEC.md` section 8) are applied as keyword cues to each row's exposure definition. Mechanical, not a validated coding; nothing in `effect_sizes.csv` changes.", '',
         "| Family | Spec wording | Rows | With a cue | Outside the wording |", "|---|---|---|---|---|"]
    for f in CUES:
        k = sum(by[f].values()); o = by[f]['outside the definition wording']
        L.append(f"| {f} | {DEF[f]} | {k} | {k - o} | {o} |")
    L += ['', f"**{len(out)} of {len(rows)} family-assigned rows sit outside their family's wording.** No family reached pooling (Phase 11), so this does not alter any estimate; it matters for how the SWiM write-ups describe the families: "
          "Family B in particular is described as 'administrative assistance' while most of its six studies test participation, trust, network capital or external funding. "
          "The SWiM texts already say the mechanisms are distinct (`family_B_swim_synthesis_2026-09-28.md`); this adds that most do not match the family's own definition. "
          "Options: (a) rename the families to describe what the rows actually test, (b) move outside rows to the non-fit group, (c) keep as is and state in the methods that families are loose groupings for write-up only (`DECISIONS_AND_OPEN_ITEMS.md` A21).", '',
          "## Rows outside their family's wording", "", "| Study | Family | Outcome | Exposure |", "|---|---|---|---|"]
    L += [f"| {r['study_id']} | {r['synthesis_family']} | {r['outcome_family']} | {r['exposure_definition'][:110]} |" for r in out]
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    rows = build()
    with open(OUT_CSV, 'w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, lineterminator='\n'); w.writeheader(); w.writerows(rows)
    OUT_MD.write_text(render(rows), encoding='utf-8')
    print(f'wrote {OUT_CSV.relative_to(cf.ROOT)} ({len(rows)} rows) and {OUT_MD.name}')
