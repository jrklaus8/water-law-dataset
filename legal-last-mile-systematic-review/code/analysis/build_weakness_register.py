#!/usr/bin/env python3
"""Weakness register: the review's known weak points, stated frankly, each with the evidence to check it and a concrete way to test or break it.

Reads code/analysis/weakness_register_source.csv (hand-written; edit it, not the outputs), replaces {tokens} with the computed figures so the numbers cannot go stale, and writes
00_admin/WEAKNESS_REGISTER.csv (for filtering and joining) and 00_admin/WEAKNESSES.md (for reading). The register was drafted by the AI from the repository's own records; the severity column is the
AI's judgment, and the researcher has not yet rated it.

Run from legal-last-mile-systematic-review/:  python3 code/analysis/build_weakness_register.py
"""
import csv
import io
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import current_figures as cf  # noqa: E402
import build_study_audit_trail as bsat  # noqa: E402

ROOT = cf.ROOT
SOURCE = Path(__file__).parent / 'weakness_register_source.csv'
OUT_CSV = ROOT / '00_admin/WEAKNESS_REGISTER.csv'
OUT_MD = ROOT / '00_admin/WEAKNESSES.md'
SEVERITY_ORDER = {'high': 0, 'medium': 1, 'low': 2}


def tokens():
    F = cf.compute()
    ta = cf.read('ta')
    ft = cf.read('ft')
    em = cf.read('em')
    audit = bsat.rows()
    t = {k: v for k, v in F.items() if isinstance(v, (int, str))}
    dec = [r for r in ft if r['final_decision'] in ('include', 'exclude')]
    t.update({
        'ta_ai_exclusions_unchecked': sum(r['title_abstract_decision'] == 'exclude' and not r['reviewer_2'] for r in ta),
        'ai_only_includes': F['full_text_include'] - F['reviewer_2_confirmed_includes'] - F['human_adjudicated_includes'],
        'ai_only_excludes': F['full_text_exclude'] - F['human_adjudicated_excludes'],
        'abstract_only': F['abstract_only_extractions'],
        'sparse_flagged': sum(r['in_sparse_audit'] == 'yes' for r in audit),
        'no_location': sum(r['source_location_recorded'] == 'no' for r in audit),
        'rule_based_rob': sum(r['rob_depth'] == 'rule-based batch rating' for r in audit),
        'legal_framework': F['tools']['Legal Framework'],
        'jbi_total': F['tools']['JBI Cross-Sectional'],
        'jbi_high': F['jbi_high_concern'],
        'multiple_mech': sum(r['mechanism_family'] == 'multiple' for r in em),
        'legacy_labels': sum(r['reviewer_1'] in ('Claude', 'claude') for r in dec),
        'fam_a': F['effect_size_by_family']['A'], 'fam_b': F['effect_size_by_family']['B'], 'fam_c': F['effect_size_by_family']['C'],
    })
    return {k: (f'{v:,}' if isinstance(v, int) else v) for k, v in t.items()}


def resolve(text, t):
    return re.sub(r'\{(\w+)\}', lambda m: t[m.group(1)], text)


def rows():
    t = tokens()
    with open(SOURCE, newline='', encoding='utf-8') as f:
        src = list(csv.DictReader(f))
    return [{k: resolve(v, t) for k, v in r.items()} for r in src]


def first_sentence(text, n=170):
    s = re.split(r'(?<=[a-z0-9\)])\.\s', text, maxsplit=1)[0].rstrip('.')
    return s if len(s) <= n else s[:n - 1].rstrip() + '…'


def render():
    data = rows()
    cols = list(data[0].keys())
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=cols, lineterminator='\n')
    w.writeheader()
    w.writerows(data)
    high = [r for r in data if r['severity_ai_judgment'] == 'high']
    md = [
        '# Weaknesses of this review, stated frankly', '',
        '*Generated by `code/analysis/build_weakness_register.py` from `code/analysis/weakness_register_source.csv` (edit the source, not this file); numbers are filled in from the databases. The data are in `WEAKNESS_REGISTER.csv`.*', '',
        '**Why this page exists.** The aim of this project is to be as open as it is possible to be about what was done and how far it can be checked, so that other researchers can find the weak points and do better. '
        'Each entry below says what the weakness is, why it matters, which way it could bias the findings (where that is knowable), the files that show it, a concrete way to test or break it, and what would resolve it.', '',
        '**Who wrote it.** The AI drafted this register from the repository\'s own records. The severity column is **the AI\'s judgment**, not the researcher\'s or an independent reviewer\'s; the researcher has not yet rated it. If you disagree with a rating or find a weakness that is missing, say so: it is a finding, not an insult.', '',
        '**How to challenge or extend it.** Pick an ID, run the test in its "how to test or break it" cell, and report the result with the ID (see `../START_HERE.md` §7). To add a weakness, add a row to `code/analysis/weakness_register_source.csv`.', '',
        f'## Where I would attack first (AI\'s judgment: {len(high)} of {len(data)} rated high)', '',
    ]
    md += [f"- **{r['id']}** ({r['stage']}): {first_sentence(r['weakness'], 150)}" for r in high]
    md += ['', '## All weaknesses', '', '| ID | Stage | Severity (AI) | Weakness | Status |', '|---|---|---|---|---|']
    md += [f"| [{r['id']}](#{r['id'].lower()}) | {r['stage']} | {r['severity_ai_judgment']} | {first_sentence(r['weakness'])} | {r['status']} |" for r in data]
    md += ['', '## Details', '']
    for r in data:
        ev = ', '.join(f'`{p.strip()}`' for p in r['evidence'].split(';') if p.strip())
        md += [f"### {r['id']}", '', f"**{r['stage']}.** {r['weakness']}", '',
               f"- **Why it matters:** {r['why_it_matters']}", f"- **Likely direction of bias:** {r['likely_direction_of_bias']}", f"- **Evidence:** {ev}",
               f"- **How to test or break it:** {r['how_to_test_or_break_it']}", f"- **What would resolve it:** {r['what_would_resolve_it']}",
               f"- **Status:** {r['status']}. **Who can resolve it:** {r['who_can_resolve']}. **Severity (AI's judgment):** {r['severity_ai_judgment']}.", '']
    return buf.getvalue(), '\n'.join(md)


def main():
    csv_text, md_text = render()
    OUT_CSV.write_text(csv_text, encoding='utf-8', newline='')
    OUT_MD.write_text(md_text, encoding='utf-8')
    print(f'wrote {OUT_CSV.name} ({csv_text.count(chr(10)) - 1}... rows) and {OUT_MD.name}'.replace('... rows', ' rows'))


if __name__ == '__main__':
    main()
