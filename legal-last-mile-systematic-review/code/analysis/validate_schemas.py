def get_generated_schemas(root: Path) -> dict[str, list[str]]:
    dedup_mod = load_module(root / "code/search/deduplicate.py", "deduplicate")
    ingest_mod = load_module(root / "code/screening/init_screening_db.py", "init_screening_db")
    return {
        "01_search/deduplicated/deduplicated_records.csv": dedup_mod.OUTPUT_FIELDS,
        "01_search/deduplicated/merge_log.csv": dedup_mod.MERGE_LOG_FIELDS,
        "02_screening/title_abstract/screening_database.csv": ingest_mod.SCHEMA,
    }


def read_header(path: Path) -> list[str] | None:
    if not path.exists():
        return None
    with path.open(newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        return next(reader, None)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2],
                         help="Path to legal-last-mile-systematic-review/ (default: computed from this script's location)")
    args = parser.parse_args()
    root = args.root.resolve()

    schemas = dict(HARDCODED_SCHEMAS)
    schemas.update(get_generated_schemas(root))

    problems = 0
    for rel_path, expected in sorted(schemas.items()):
        path = root / rel_path
        actual = read_header(path)
        if actual is None:
            print(f"MISSING: {rel_path} does not exist.")
            problems += 1
            continue
        if actual != expected:
            print(f"MISMATCH: {rel_path}")
            missing = [f for f in expected if f not in actual]
            extra = [f for f in actual if f not in expected]
            if missing:
                print(f"  documented but not present: {missing}")
            if extra:
                print(f"  present but not documented: {extra}")
            if not missing and not extra:
                print(f"  same fields, different order: expected {expected}, got {actual}")
            problems += 1
        else:
            print(f"OK: {rel_path} ({len(actual)} fields)")

    if problems:
        print(f"\n{problems} schema problem(s) found.")
        return 1
    print(f"\nAll {len(schemas)} checked files match their documented/generated schema.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
