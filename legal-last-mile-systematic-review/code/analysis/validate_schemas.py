#!/usr/bin/env python3
"""Check every project CSV's actual header against its documented schema.

This project's schema has already changed once since launch (the `url`
field was added to the screening database and its upstream pipeline after
real candidate records showed DOI alone wasn't enough -- see
CHANGELOG.md, 2026-08-25). Schema drift between what DATA_DICTIONARY.md
says and what a CSV file actually contains is exactly the kind of quiet
error that would only surface much later, e.g. as a KeyError deep in an
analysis script, or worse, as silently misaligned columns. This script
exists to catch that early and cheaply.

Where a schema is generated by a script (deduplicate.py,
init_screening_db.py), the expected header is imported from that script
directly rather than re-declared here, so there is exactly one source of
truth for those two. The other CSVs have no generating script yet, so
their expected headers are declared here and must be kept in sync with
DATA_DICTIONARY.md by hand.

Standard library only, consistent with this repository's existing
scrapers (see ../../../README.md).

USAGE
-----
    python3 validate_schemas.py [--root ../..]

Exits non-zero if any checked file is missing, or has a header that
doesn't match, so it can be used as a pre-commit or CI check.
"""
from __future__ import annotations

import argparse
import csv
import importlib.util
import sys
from pathlib import Path


def load_module(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


